import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { generateKeyPairSync, sign } from 'node:crypto';
import { readFile, writeFile, mkdir, cp, rm, access } from 'node:fs/promises';
import { join } from 'node:path';
import { inventory, sha256 } from '../../scripts/package-release.mjs';
import { verifyRelease } from '../../scripts/verify-release.mjs';
import { runWorkflow, engineCommand, workflowCommands } from '../../scripts/clone-workflow.mjs';

export async function runUpgradeRecovery({ root, work, candidateArtifacts, candidateCommit, runtime, start, stop, browser }) {
  await mkdir(work);
  const fixture = JSON.parse(await readFile(join(root, 'tests/fixtures/attestara/C35/cases.json')));
  const baselineCommit = fixture.baseline_commit;
  assert.match(baselineCommit, /^[a-f0-9]{40}$/);
  const commandOffset = workflowCommands.length;
  const run = (command, args, cwd = root) => execFileSync(command, args, { cwd, encoding: 'utf8', timeout: 600000, maxBuffer: 16 * 1024 * 1024 });
  const baselineSource = join(work, 'baseline-source');
  run('git', ['clone', '--quiet', '--shared', '--no-checkout', root, baselineSource]);
  run('git', ['checkout', '--quiet', '--detach', baselineCommit], baselineSource);
  run(process.execPath, [process.env.npm_execpath, 'run', 'package'], baselineSource);
  const baselineArtifacts = join(baselineSource, 'dist/packages', baselineCommit);
  const keys = generateKeyPairSync('ed25519');
  const publicKey = Buffer.from(keys.publicKey.export({ format: 'jwk' }).x, 'base64url').toString('hex');
  const trusted = { schema_version: '1', trusted_signers: { 'synthetic-c35-test': publicKey } };
  const trust = join(work, 'independently-configured-trust.json');
  await writeFile(trust, JSON.stringify(trusted));
  const releases = [];
  for (const [directory, commit, label] of [[baselineArtifacts, baselineCommit, 'baseline'], [candidateArtifacts, candidateCommit, 'candidate']]) {
    const sums = await readFile(join(directory, 'SHA256SUMS.txt'));
    const detached = { schema_version: '1', signer_id: 'synthetic-c35-test', public_key_hex: publicKey, signature_hex: sign(null, sums, keys.privateKey).toString('hex') };
    const signature = join(work, label + '-signature.json');
    await writeFile(signature, JSON.stringify(detached));
    const options = { directory, signature, trust, expectedSourceCommit: commit, freshness: 'fresh' };
    const result = await verifyRelease(options);
    assert.equal(result.exitCode, 0, JSON.stringify(result));
    assert.equal((await verifyRelease({ ...options, freshness: 'stale' })).exitCode, 1);
    releases.push({ commit, signature: detached, checksums_sha256: sha256(sums), assessment: result.assessment, files: await inventory(directory) });
  }
  const baseline = join(work, 'installed-baseline'); await mkdir(baseline);
  run('tar', ['-xzf', join(baselineArtifacts, 'attestara-' + baselineCommit + '-linux-x64.tar.gz'), '-C', baseline]);
  const store = join(work, 'store');
  await start(baseline, store);
  const state = runWorkflow(baseline, work, store);
  await stop();
  const beforeUpgrade = await inventory(store);
  const url = await start(runtime, store);
  assert.equal(engineCommand(runtime, ['verify', '--store', store, '--operation-id', 'release-1']).stdout, state.first);
  assert.deepEqual(await inventory(store), beforeUpgrade);
  const newer = join(work, 'newer-input');
  await cp(join(runtime, 'tests/fixtures/attestara/C30'), newer, { recursive: true });
  const subject = Buffer.from('Synthetic C35 newer accepted subject.\n');
  await writeFile(join(newer, 'subject.txt'), subject);
  const input = JSON.parse(await readFile(join(newer, 'manifest.json')));
  input.release_id = 'attestara-c35-newer'; input.source_revision = 'synthetic-c35-2';
  input.subject_digest = 'sha256:' + sha256(subject);
  const ref = input.files.find(file => file.path === 'subject.txt');
  ref.digest = input.subject_digest; ref.size_bytes = subject.length;
  await writeFile(join(newer, 'manifest.json'), JSON.stringify(input));
  const args = ['evaluate', '--input', join(newer, 'manifest.json'), '--files', newer, '--policy', join(newer, 'rule.json'), '--evidence', join(newer, 'evidence.json'), '--freshness', 'fresh', '--store', store, '--operation-id', 'release-2'];
  const second = engineCommand(runtime, args).stdout;
  assert.notEqual(second, state.first);
  const accepted = await inventory(store);
  assert.equal(engineCommand(runtime, args).stdout, second);
  const view = async (address, passport) => {
    const page = await browser.newPage({ viewport: { width: 360, height: 800 } });
    try {
      const writes = []; page.on('request', request => { if (request.method() !== 'GET') writes.push(request.url()); });
      await page.goto(address + '/#passport');
      await page.getByLabel('Choose passport file').setInputFiles({ name: 'newer.json', mimeType: 'application/json', buffer: Buffer.from(passport) });
      await page.getByRole('heading', { name: input.release_id }).waitFor();
      await page.getByText('Viewer assessment: Unverified').waitFor();
      assert.deepEqual(writes, []);
    } finally { await page.close(); }
  };
  await view(url, second);
  await stop(); await start(runtime, store);
  assert.equal(engineCommand(runtime, ['verify', '--store', store, '--operation-id', 'release-2']).stdout, second);
  await stop();
  const rollbackURL = await start(baseline, store);
  for (const [id, passport] of [['release-1', state.first], ['release-2', second]]) assert.equal(engineCommand(baseline, ['verify', '--store', store, '--operation-id', id]).stdout, passport);
  await view(rollbackURL, second);
  assert.deepEqual(await inventory(store), accepted, 'rollback retains every newer accepted byte');
  engineCommand(baseline, ['restore', '--backup', state.backup, '--store', store, '--operation-id', 'release-1'], 3);
  assert.deepEqual(await inventory(store), accepted, 'old backup never overwrites newer state');
  const restored = join(work, 'restored');
  assert.equal(engineCommand(baseline, ['restore', '--backup', state.backup, '--store', restored, '--operation-id', 'release-1']).stdout, state.first);
  const newBackup = join(work, 'newer-backup');
  assert.equal(engineCommand(baseline, ['export', '--store', store, '--operation-id', 'release-2', '--output', newBackup]).stdout, second);
  assert.equal(engineCommand(runtime, ['restore', '--backup', newBackup, '--store', join(work, 'newer-restored'), '--operation-id', 'release-2']).stdout, second);
  const old = { directory: baselineArtifacts, signature: join(work, 'baseline-signature.json'), trust, expectedSourceCommit: candidateCommit, freshness: 'fresh' };
  assert.equal((await verifyRelease(old)).exitCode, 2, 'old signed version fails the independently selected newer expectation');
  const incomplete = join(work, 'incomplete-install'); await mkdir(incomplete);
  await writeFile(join(incomplete, 'release.json'), '{}');
  assert.equal((await verifyRelease({ ...old, directory: incomplete })).exitCode, 2);
  assert.equal(engineCommand(baseline, ['verify', '--store', store, '--operation-id', 'release-2']).stdout, second);
  await stop();
  const incompatible = join(work, 'unsupported-store'); await cp(store, incompatible, { recursive: true });
  const path = join(incompatible, 'manifest');
  const incompatibleBytes = (await readFile(path, 'utf8')).replace('{"schema_version":1}', '{"schema_version":2}');
  await writeFile(path, incompatibleBytes);
  for (const installed of [baseline, runtime]) engineCommand(installed, ['verify', '--store', incompatible, '--operation-id', 'release-2'], 3);
  assert.equal(await readFile(path, 'utf8'), incompatibleBytes);
  assert.deepEqual(await inventory(store), accepted);
  const hostile = join(work, 'source-sentinel');
  await cp(newer, hostile, { recursive: true });
  const sentinel = join(work, 'must-not-exist');
  const payload = Buffer.from('#!/bin/sh\ntouch ' + sentinel + '\n');
  await writeFile(join(hostile, 'subject.txt'), payload);
  input.subject_digest = 'sha256:' + sha256(payload); ref.digest = input.subject_digest; ref.size_bytes = payload.length;
  await writeFile(join(hostile, 'manifest.json'), JSON.stringify(input));
  engineCommand(runtime, ['evaluate', '--input', join(hostile, 'manifest.json'), '--files', hostile, '--policy', join(hostile, 'rule.json'), '--evidence', join(hostile, 'evidence.json'), '--freshness', 'fresh']);
  await assert.rejects(access(sentinel));
  await rm(incomplete, { recursive: true });
  return { passed: true, baseline_commit: baselineCommit, candidate_commit: candidateCommit, license: 'Apache-2.0', trust: trusted, releases, store_before_upgrade: beforeUpgrade, store_after_new_write_and_rollback: accepted, passport_sha256: [sha256(state.first), sha256(second)], browser: browser.version(), commands: workflowCommands.slice(commandOffset), checks: fixture.expected_checks, limits: ['Temporary test key, not the maintainer release identity.', 'Same supported Linux host; independent onboarding remains C36.', 'Expected source and freshness are explicit operator inputs, not persistent anti-replay authority.'] };
}
